// Сообщения, которыми телефон и книга обмениваются через сервер.
// Этот файл — общий для обоих клиентов: формат описан в одном месте.

/** Статья в режиме чтения, готовая к показу на книге. */
export interface Article {
  /** Адрес, по которому статью добавили; по нему телефон узнаёт её в списке. */
  id: string;
  title: string;
  byline: string;
  /** Дата публикации (ISO 8601) или пустая строка. */
  published: string;
  /** Оценка времени чтения в минутах. */
  readingTime: number;
  sourceUrl: string;
  /**
   * Язык текста, например "ru". По нему браузер книги расставляет переносы;
   * у статей, сохранённых до появления этого поля, его нет.
   */
  lang?: string;
  html: string;
}

/** Подстановки в текст сообщения, например { title: "…" }. */
export type Args = Record<string, string | number>;

/** Каким движением пальца листают страницы на книге. */
export type Swipe = "vertical" | "horizontal";

/** На сколько градусов по часовой стрелке повёрнут экран книги. */
export type Rotation = 0 | 90 | 180 | 270;
export const ROTATIONS: readonly Rotation[] = [0, 90, 180, 270];

/**
 * Канал "book": телефон → книга. В каждом сообщении едут язык интерфейса
 * телефона (lang) и настройки книги (swipe, rotate), какими телефон их
 * запомнил. Язык книга перенимает всегда, настройки — только если своих
 * у неё нет (новая книга или очищенная память): так телефон возвращает
 * книге её настройки. В канале помнится только последнее сообщение,
 * поэтому отдельного сообщения для этого нет.
 */
export type BookMessage = BookEvent & { lang?: string; swipe?: string; rotate?: number };

type BookEvent =
  /** Телефон отсканировал код и теперь связан с этой книгой. */
  | { type: "paired" }
  /** Шаг загрузки. key — ключ словаря `status.*`: книга переводит его сама. */
  | { type: "status"; key: string; args?: Args }
  /** Загрузка не удалась. code — ключ словаря `errors.*`. */
  | { type: "error"; code: string; args?: Args }
  /**
   * anchor — номер блока текста, с которого продолжить чтение. error — что
   * не удалось сделать по просьбе книги (открыть ссылку как статью): ошибка
   * едет вместе со статьёй, чтобы отдельное сообщение не заняло её место
   * в канале и перезагруженная книга не осталась без статьи.
   */
  | { type: "article"; article: Article; anchor: number; error?: { code: string; args?: Args } };

/** Место чтения: номер блока текста и доля прочитанного. */
export interface Progress {
  articleId: string;
  anchor: number;
  percent: number;
}

/**
 * Канал "phone": книга → телефон. В каждом сообщении едут настройки книги
 * (swipe, rotate): их меняют в меню книги, а телефон запоминает, чтобы
 * потом вернуть.
 */
export type PhoneMessage = PhoneEvent & { swipe?: string; rotate?: number };

type PhoneEvent =
  | ({ type: "progress" } & Progress)
  /**
   * На книге изменили настройки. Сообщение занимает в канале место
   * прогресса, поэтому несёт его с собой.
   */
  | { type: "settings"; progress: Progress | null }
  /**
   * На книге нажали на ссылку в статье и попросили телефон открыть её:
   * article=true — как статью на книге (режим чтения делает телефон),
   * false — в браузере телефона.
   *
   * Как и при выходе, последний прогресс едет вместе с сообщением: оно
   * занимает в канале место прогресса.
   */
  | { type: "link"; url: string; article: boolean; progress: Progress | null }
  /**
   * На книге нажали «Выйти». В канале помнится только последнее сообщение,
   * поэтому последний прогресс едет вместе с ним, чтобы не потеряться.
   */
  | { type: "unpaired"; progress: Progress | null };

export type Channel = "book" | "phone";
